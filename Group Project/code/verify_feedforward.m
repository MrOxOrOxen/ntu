function verify_feedforward
% Reproduce the complete project and verify the feedforward implementation.
root = fileparts(mfilename('fullpath'));
callerFolder = pwd;
restoreFolder = onCleanup(@() cd(callerFolder));
cd(root);
run_project;
folder = fullfile(root,'results_required');
saved = load(fullfile(folder,'step3_design.mat'));
observer = saved.observer;
baseline = saved.baseline;
design = saved.design;
A = observer.A;
B = observer.B;
C = observer.C;
K = design.Kx;
assert(isequal(baseline.Q,diag([10 300 1 10])) && baseline.R==1);
assert(norm(K-baseline.K,inf)<1e-12);
assert(isequal(observer.Qn,10*eye(2)) && isequal(observer.Rn,eye(2)));
assert(norm(A*design.Nx+B*design.Nu,inf)<1e-12);
assert(abs(C(1,:)*design.Nx-1)<1e-12);
assert(abs(design.Nbar-(design.Nu+K*design.Nx))<1e-12);
assert(abs(design.dcGain-1)<1e-10);
Acl = [A-B*K B*K; zeros(4) A-observer.L*C];
assert(all(real(eig(Acl))<0));

model = 'Step3_Feedforward';
load_system(fullfile(root,[model '.slx']));
modelCleanup = onCleanup(@() close_system(model,0));
set_param(model,'SimulationCommand','update');
assert(isempty(find_system(model,'SearchDepth',1,'BlockType','Integrator')));
assert(strcmp(get_param([model '/Reference feedforward'],'Gain'),'Nbar'));
assert(strcmp(get_param([model '/State feedback'],'Gain'),'-Kx'));
assert(strcmp(get_param([model '/Voltage limit'],'UpperLimit'),'voltageLimit'));
ws = get_param(model,'ModelWorkspace');
assert(norm(getVariable(ws,'Kx')-baseline.K,inf)<1e-12);
assert(abs(getVariable(ws,'Nbar')-design.Nbar)<1e-12);
assert(norm(getVariable(ws,'A_obs')-observer.A_obs,inf)<1e-12);

tracking = readtable(fullfile(folder,'step3_reference_tracking_samples.csv'));
summary = readtable(fullfile(folder,'step3_reference_tracking_summary.csv'));
balance = readtable(fullfile(folder,'step2_balance_samples.csv'));
assert(all(isfinite(tracking{:,:}),'all'));
assert(isequal(round(summary.Reference_deg)',[0 20 -15 30 0]));
assert(all(summary.TailMaxError_deg<0.1));
assert(all(summary.TailMaxTilt_deg<0.1));
assert(max(abs(tracking.Command_V))<design.voltageLimit);
tail = balance.Time_s>=balance.Time_s(end)-1;
metrics = struct;
metrics.K = K;
metrics.Q = diag(baseline.Q)';
metrics.R = baseline.R;
metrics.Nx = design.Nx';
metrics.Nu = design.Nu;
metrics.Nbar = design.Nbar;
metrics.dcGain = design.dcGain;
poles = eig(A-B*K);
metrics.regulatorPoles = [real(poles) imag(poles)];
poles = eig(A-observer.L*C);
metrics.observerPoles = [real(poles) imag(poles)];
metrics.tracking = table2struct(summary);
metrics.fullRunPeakVoltage = max(abs(tracking.Command_V));
metrics.switchedPeakTilt = max(summary.PeakTilt_deg(2:end));
metrics.switchedTailError = max(summary.TailMaxError_deg(2:end));
metrics.switchedTailTilt = max(summary.TailMaxTilt_deg(2:end));
metrics.balancePeakArm = max(abs(balance.Arm_deg));
metrics.balancePeakVoltage = max(abs(balance.Command_V));
metrics.balanceTailArm = max(abs(balance.Arm_deg(tail)));
metrics.balanceTailTilt = max(abs(balance.Pendulum_deg(tail)));
metrics.balanceArmSpeedError = max(abs(balance.ArmSpeed_rad_s(tail)-balance.EstimatedArmSpeed_rad_s(tail)));
metrics.balancePendulumSpeedError = max(abs(balance.PendulumSpeed_rad_s(tail)-balance.EstimatedPendulumSpeed_rad_s(tail)));
metrics.matlabVersion = version;
metrics.validation = 'MATLAB and Simulink complete-project run passed';
fid = fopen(fullfile(folder,'feedforward_validation.json'),'w');
fprintf(fid,'%s',jsonencode(metrics,PrettyPrint=true));
fclose(fid);
fprintf('FEEDFORWARD_VALIDATION_PASSED | Nbar %.8f | switched tail error %.9g deg | peak voltage %.6f V\n', ...
    design.Nbar,metrics.switchedTailError,metrics.fullRunPeakVoltage);
end
